export function pageOf<T>(content: T[], page = 0, size = 12) {
  return {
    content,
    totalPages: Math.max(1, Math.ceil(content.length / size)),
    totalElements: content.length,
    number: page,
    size,
    first: page === 0,
    last: true,
    empty: content.length === 0,
  };
}
